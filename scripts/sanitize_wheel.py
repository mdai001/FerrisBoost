"""Remove build-machine identifiers from a built wheel.

maturin records the crate as `path+file:///absolute/build/dir` in the CycloneDX
SBOM's bom-ref fields, which puts the builder's directory layout into every
released artifact. RUSTFLAGS remapping does not touch it, because the SBOM is
generated by maturin rather than by rustc.

Rewrites those refs to a stable placeholder and regenerates RECORD, since
rewriting a member invalidates its hash and size.

Also removes the ELF `.comment` section from native modules. The linker fills
it with toolchain banners (the distro's exact GCC build, rustc version and
commit, linker version), which identify the build machine and are not needed to
load or run the module. Requires `objcopy` (binutils).

    sanitize_wheel.py <wheel> [--check]
"""
import base64, csv, hashlib, io, os, re, subprocess, sys, tempfile, zipfile

PLACEHOLDER = "path+file:///src"

def digest(data: bytes) -> str:
    return "sha256=" + base64.urlsafe_b64encode(hashlib.sha256(data).digest()).decode().rstrip("=")

def elf_has_comment(data: bytes) -> bool:
    """True when an ELF image still carries a `.comment` section."""
    with tempfile.TemporaryDirectory() as d:
        so = os.path.join(d, "module.so")
        with open(so, "wb") as f:
            f.write(data)
        out = subprocess.run(["readelf", "-S", "-W", so], check=True,
                             capture_output=True, text=True).stdout
    return any(line.split("]", 1)[-1].split()[:1] == [".comment"]
               for line in out.splitlines() if "]" in line)

def strip_comment(data: bytes) -> bytes:
    with tempfile.TemporaryDirectory() as d:
        so = os.path.join(d, "module.so")
        with open(so, "wb") as f:
            f.write(data)
        subprocess.run(["objcopy", "--remove-section=.comment", so], check=True)
        with open(so, "rb") as f:
            return f.read()

def sanitize(path: str, check_only: bool = False) -> int:
    src = zipfile.ZipFile(path)
    members = [(i, src.read(i.filename)) for i in src.infolist()]
    src.close()

    changed = []
    out = []
    for info, data in members:
        if "cyclonedx" in info.filename and b"path+file://" in data:
            new = re.sub(rb'path\+file://[^"#]*', PLACEHOLDER.encode(), data)
            if new != data:
                changed.append(info.filename)
                data = new
        if data[:4] == b"\x7fELF" and elf_has_comment(data):
            changed.append(info.filename)
            if not check_only:
                data = strip_comment(data)
        out.append((info, data))

    if check_only:
        return len(changed)
    if not changed:
        return 0

    # RECORD must be rebuilt: the rewritten member's hash and size changed.
    record_name = next(n for n, _ in [(i.filename, d) for i, d in out] if n.endswith(".dist-info/RECORD"))
    rows = []
    for info, data in out:
        if info.filename == record_name:
            continue
        rows.append([info.filename, digest(data), str(len(data))])
    rows.append([record_name, "", ""])
    buf = io.StringIO()
    csv.writer(buf, lineterminator="\n").writerows(rows)
    record_bytes = buf.getvalue().encode()

    tmp = path + ".tmp"
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as z:
        for info, data in out:
            z.writestr(info, record_bytes if info.filename == record_name else data)
    os.replace(tmp, path)
    return len(changed)

if __name__ == "__main__":
    wheel = sys.argv[1]
    check = "--check" in sys.argv
    n = sanitize(wheel, check)
    if check:
        print(f"{n} member(s) still carry build paths or toolchain banners")
        sys.exit(1 if n else 0)
    print(f"sanitised {n} member(s) in {os.path.basename(wheel)}")
